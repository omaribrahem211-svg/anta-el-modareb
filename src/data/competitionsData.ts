/**
 * Resolves the authentic Domestic National Cup definition for any country in the game.
 */
export function getDomesticCupDefinitionForCountry(country: string): CompetitionDefinition {
  const clean = (country || 'مصر').trim();
  const mapByCountry: Record<string, string> = {
    'مصر': 'egy_cup',
    'السعودية': 'sau_kings_cup',
    'المملكة العربية السعودية': 'sau_kings_cup',
    'الإمارات': 'uae_pres_cup',
    'قطر': 'qat_amir_cup',
    'المغرب': 'mar_throne_cup',
    'تونس': 'tun_cup',
    'الجزائر': 'alg_cup',
    'إنجلترا': 'eng_fa_cup',
    'إسبانيا': 'esp_copa',
    'إيطاليا': 'ita_coppa',
    'ألمانيا': 'ger_dfb_pokal',
    'فرنسا': 'fra_coupe',
    'البرازيل': 'bra_copa',
    'الأرجنتين': 'arg_copa',
  };

  const compId = mapByCountry[clean];
  if (compId && GLOBAL_COMPETITIONS[compId]) {
    return GLOBAL_COMPETITIONS[compId];
  }

  const found = Object.values(GLOBAL_COMPETITIONS).find(
    c => c.type === 'cup' && (c.country === clean || clean.includes(c.country) || c.country.includes(clean))
  );
  if (found) return found;

  return {
    id: `cup_${clean}`,
    name: `كأس ${clean} الوطنية`,
    shortName: `كأس ${clean}`,
    type: 'cup',
    country: clean,
    countryCode: 'CUP',
    continent: 'Global',
    totalTeams: 32,
    championPrize: 3000000,
    runnerUpPrize: 1500000,
    reputation: 80,
    formatDescription: `بطولة الكأس الوطنية الرسمية في ${clean} بنظام خروج المغلوب`,
    iconName: 'Shield',
    color: '#dc2626',
  };
}
