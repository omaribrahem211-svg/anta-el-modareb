export function generateLeagueSchedule(teams: Club[]): Fixture[] {
  const fixtures: Fixture[] = [];
  const teamIds = teams.map(t => t.id);
  const n = teamIds.length;
  let fixtureId = 1;

  // Round Robin tournament schedule (ذهاب وإياب: 38 جولة للدوري المكون من 20 فريقاً)
  // For n=20 teams, round robin is 19 rounds (First leg), and 19 rounds (Second leg) = 38 rounds
  const rounds = (n - 1) * 2;
  const halfRounds = n - 1;

  const indices = Array.from({ length: n }, (_, i) => i);

  for (let r = 0; r < halfRounds; r++) {
    const roundNumber = r + 1;
    for (let i = 0; i < n / 2; i++) {
      const homeIdx = (r + i) % (n - 1);
      let awayIdx = (n - 1 - i + r) % (n - 1);
      if (i === 0) {
        awayIdx = n - 1;
      }
      
      const homeId = teamIds[indices[homeIdx]];
      const awayId = teamIds[indices[awayIdx]];

      fixtures.push({
        id: `fix_${fixtureId++}`,
        round: roundNumber,
        homeTeamId: homeId,
        awayTeamId: awayId,
        isPlayed: false,
      });
    }
  }

  // Second Leg (الإياب) - reverse home/away
  for (let r = 0; r < halfRounds; r++) {
    const roundNumber = r + halfRounds + 1;
    const firstLegMatches = fixtures.filter(f => f.round === r + 1);
    for (const match of firstLegMatches) {
      fixtures.push({
        id: `fix_${fixtureId++}`,
        round: roundNumber,
        homeTeamId: match.awayTeamId,
        awayTeamId: match.homeTeamId,
        isPlayed: false,
      });
    }
  }

  return fixtures;
}

